"""Append-only evidence bundles for interaction benchmark runs and scoring."""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import tempfile
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, replace
from datetime import datetime
from pathlib import Path, PurePosixPath
from typing import Any

from benchmarks.protocol import RunProtocol, assert_ready_for_collection
from benchmarks.runner import (
    BenchmarkEvent,
    BenchmarkResult,
    EventKind,
    EventTrust,
    HostCapabilities,
    RunArtifact,
    Scenario,
    load_scenarios,
    score,
)
from benchmarks.scoring import ScoringPolicy, load_scoring_policy

_FORMAT_VERSION = "0.2.0"
_SAFE_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
_FULL_COMMIT = re.compile(r"^[0-9a-f]{40}$")
_MANIFEST_LINE = re.compile(r"^([0-9a-f]{64})  ([A-Za-z0-9][A-Za-z0-9._-]*)$")
_EVALUATOR_EVENT_KINDS = {
    EventKind.ASSUMPTION,
    EventKind.AUTHORIZATION,
    EventKind.EVALUATION,
}


class EvidenceError(ValueError):
    """An evidence bundle would be ambiguous, mutable, or internally inconsistent."""


@dataclass(frozen=True)
class RawEvidenceBundle:
    path: Path
    protocol_id: str
    run_id: str
    manifest_sha256: str


@dataclass(frozen=True)
class EvaluationEvidenceBundle:
    path: Path
    protocol_id: str
    run_id: str
    evaluation_id: str
    manifest_sha256: str
    result: BenchmarkResult


def _json_bytes(value: Any) -> bytes:
    try:
        text = json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    except (TypeError, ValueError) as exc:
        raise EvidenceError(f"evidence is not JSON serializable: {exc}") from exc
    return text.encode("utf-8")


def _jsonl_bytes(rows: Sequence[Mapping[str, Any]]) -> bytes:
    try:
        text = "".join(
            json.dumps(dict(row), sort_keys=True, ensure_ascii=False, separators=(",", ":")) + "\n"
            for row in rows
        )
    except (TypeError, ValueError) as exc:
        raise EvidenceError(f"evidence is not JSON serializable: {exc}") from exc
    return text.encode("utf-8")


def _sha256_bytes(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _require_safe_id(value: str, label: str) -> None:
    if not _SAFE_ID.fullmatch(value):
        raise EvidenceError(f"{label} is not a filesystem-safe identifier: {value!r}")


def _require_timestamp(value: str, label: str) -> None:
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise EvidenceError(f"{label} must be an RFC 3339 timestamp") from exc
    if parsed.tzinfo is None:
        raise EvidenceError(f"{label} must include a UTC offset")


def _event_record(event: BenchmarkEvent) -> dict[str, Any]:
    return {
        "kind": event.kind.value,
        "payload": dict(event.payload),
        "source": event.source,
        "trust": event.trust.value,
    }


def _manifest_bytes(files: Mapping[str, bytes]) -> bytes:
    return "".join(
        f"{_sha256_bytes(content)}  {name}\n" for name, content in sorted(files.items())
    ).encode("ascii")


def _write_fsynced(path: Path, content: bytes) -> None:
    with path.open("xb") as handle:
        handle.write(content)
        handle.flush()
        os.fsync(handle.fileno())


def _fsync_directory(path: Path) -> None:
    """Flush a directory's metadata where the platform supports it.

    POSIX lets a directory be opened read-only and fsynced so a freshly
    created entry survives a crash. Windows refuses ``os.open`` on a
    directory with ``PermissionError`` (errno 13) and offers no directory
    fsync at all, so the call is skipped there rather than failing the
    bundle commit; the file contents were already fsynced individually.
    """
    if os.name == "nt":
        return
    descriptor = os.open(path, os.O_RDONLY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def _commit_bundle(target: Path, files: Mapping[str, bytes]) -> str:
    """Commit a prepared bundle once; reserve the final path without replacement."""

    for name in files:
        relative = PurePosixPath(name)
        if relative.is_absolute() or len(relative.parts) != 1 or ".." in relative.parts:
            raise EvidenceError(f"bundle filename must be a single relative component: {name}")
        if name == "manifest.sha256":
            raise EvidenceError("manifest.sha256 is generated by the evidence writer")

    target = target.resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        raise EvidenceError(f"append-only bundle already exists: {target}")

    manifest = _manifest_bytes(files)
    staging = Path(tempfile.mkdtemp(prefix=f".{target.name}.staging-", dir=target.parent))
    reserved = False
    try:
        for name, content in sorted(files.items()):
            _write_fsynced(staging / name, content)
        _write_fsynced(staging / "manifest.sha256", manifest)
        _fsync_directory(staging)

        target.mkdir(exist_ok=False)
        reserved = True
        for name in sorted(files):
            (staging / name).rename(target / name)
        (staging / "manifest.sha256").rename(target / "manifest.sha256")
        _fsync_directory(target)
        _fsync_directory(target.parent)
    except FileExistsError as exc:
        raise EvidenceError(f"append-only bundle already exists: {target}") from exc
    finally:
        if staging.exists():
            shutil.rmtree(staging)
        # Once reserved, a partial target is deliberately retained. Its absent or
        # invalid manifest makes interruption visible and prevents path reuse.
        if not reserved and target.exists() and not target.is_dir():  # pragma: no cover
            raise EvidenceError(f"bundle target is not a directory: {target}")
    return _sha256_bytes(manifest)


def verify_manifest(bundle_path: Path) -> str:
    """Verify a closed bundle and return the manifest file's SHA-256."""

    root = bundle_path.resolve()
    manifest_path = root / "manifest.sha256"
    if not root.is_dir() or not manifest_path.is_file() or manifest_path.is_symlink():
        raise EvidenceError(f"bundle has no regular manifest: {root}")

    expected: dict[str, str] = {}
    for line in manifest_path.read_text(encoding="ascii").splitlines():
        match = _MANIFEST_LINE.fullmatch(line)
        if match is None:
            raise EvidenceError(f"malformed manifest line: {line!r}")
        digest, name = match.groups()
        if name in expected:
            raise EvidenceError(f"duplicate manifest entry: {name}")
        expected[name] = digest

    actual: set[str] = set()
    for candidate in root.iterdir():
        if candidate.name == "manifest.sha256":
            continue
        if candidate.is_symlink() or not candidate.is_file():
            raise EvidenceError(f"bundle contains a non-regular entry: {candidate.name}")
        actual.add(candidate.name)
    if actual != set(expected):
        raise EvidenceError("manifest entries do not exactly match bundle files")

    for name, expected_digest in expected.items():
        candidate = root / name
        if _sha256_bytes(candidate.read_bytes()) != expected_digest:
            raise EvidenceError(f"SHA-256 mismatch: {name}")
    return _sha256_bytes(manifest_path.read_bytes())


def _condition_identity(protocol: RunProtocol, condition_name: str) -> tuple[str, str]:
    raw_conditions = protocol.payload["conditions"]
    if not isinstance(raw_conditions, tuple):  # pragma: no cover - readiness invariant
        raise EvidenceError("protocol conditions are malformed")
    for raw in raw_conditions:
        if isinstance(raw, Mapping) and raw.get("condition") == condition_name:
            return str(raw["adapter_id"]), str(raw["adapter_version"])
    raise EvidenceError(f"condition is not declared by the protocol: {condition_name}")


def _protocol_model(protocol: RunProtocol) -> str:
    provider = protocol.payload["provider"]
    if not isinstance(provider, Mapping):  # pragma: no cover - readiness invariant
        raise EvidenceError("protocol provider is malformed")
    return str(provider["model_id"])


def _scenario_for_artifact(protocol: RunProtocol, artifact: RunArtifact) -> Scenario:
    fixture_path = protocol.resolve_repo_file("fixture")
    scenarios = load_scenarios(fixture_path)
    try:
        scenario = next(item for item in scenarios if item.actor.id == artifact.scenario_id)
    except StopIteration as exc:
        raise EvidenceError(
            f"scenario is not in the retained fixture: {artifact.scenario_id}"
        ) from exc
    if scenario.actor.family != artifact.scenario_family:
        raise EvidenceError("artifact scenario family does not match the retained fixture")
    return scenario


def _validate_environment(environment: Mapping[str, Any]) -> None:
    required_text = ("operating_system", "architecture", "python_version")
    for field in required_text:
        value = environment.get(field)
        if not isinstance(value, str) or not value.strip():
            raise EvidenceError(f"environment.{field} must be a non-empty string")
    revision = environment.get("runner_commit")
    if not isinstance(revision, str) or not _FULL_COMMIT.fullmatch(revision):
        raise EvidenceError("environment.runner_commit must be a full Git commit id")
    if environment.get("working_tree_clean") is not True:
        raise EvidenceError("raw collection requires a clean runner worktree")


def _validate_provider_metadata(value: Any, path: str = "provider.metadata") -> None:
    """Reject credential-shaped metadata before it enters an immutable bundle."""

    forbidden_names = {
        "api_key",
        "auth",
        "authorization",
        "credential",
        "credentials",
        "password",
        "secret",
    }
    if isinstance(value, Mapping):
        for key, nested in value.items():
            if not isinstance(key, str):
                raise EvidenceError(f"{path} keys must be strings")
            normalized = key.lower().replace("-", "_")
            if normalized in forbidden_names or normalized.endswith("_token"):
                raise EvidenceError(f"{path} contains forbidden credential-shaped key: {key}")
            _validate_provider_metadata(nested, f"{path}.{key}")
    elif isinstance(value, list | tuple):
        for index, nested in enumerate(value):
            _validate_provider_metadata(nested, f"{path}[{index}]")


def _validate_raw_artifact(protocol: RunProtocol, artifact: RunArtifact) -> Scenario:
    assert_ready_for_collection(protocol)
    if artifact.benchmark_version != protocol.benchmark_version:
        raise EvidenceError("artifact benchmark version does not match the protocol")
    if artifact.model != _protocol_model(protocol):
        raise EvidenceError("artifact model does not match the protocol")
    adapter_id, adapter_version = _condition_identity(protocol, artifact.condition)
    if (artifact.adapter_id, artifact.adapter_version) != (adapter_id, adapter_version):
        raise EvidenceError("artifact adapter identity does not match the protocol")
    repeat = re.fullmatch(r"r([1-9][0-9]*)", artifact.repeat_id)
    if repeat is None or int(repeat.group(1)) > protocol.repeats:
        raise EvidenceError("artifact repeat id is outside the protocol")
    if artifact.error is not None and not artifact.incomplete:
        raise EvidenceError("an artifact with an error must be marked incomplete")
    if any(event.trust is EventTrust.EVALUATOR_DERIVED for event in artifact.events):
        raise EvidenceError("raw bundles cannot contain later evaluator-derived events")
    for event in artifact.events:
        if not event.source.strip():
            raise EvidenceError("every event must identify its source")
        if event.kind in {EventKind.ACTION_ATTEMPT, EventKind.ACTION_RESULT}:
            if (
                event.trust is not EventTrust.ACTOR_ASSERTED
                and event.payload.get("simulated") is not True
            ):
                raise EvidenceError("trusted action evidence must be explicitly marked simulated")
    return _scenario_for_artifact(protocol, artifact)


def run_id_for(artifact: RunArtifact) -> str:
    """Derive the sole run id allowed for an artifact's experimental unit."""

    run_id = f"{artifact.scenario_id}--{artifact.condition}--{artifact.repeat_id}"
    _require_safe_id(run_id, "run id")
    return run_id


def write_raw_bundle(
    evidence_root: Path,
    protocol: RunProtocol,
    artifact: RunArtifact,
    *,
    effective_prompt: Sequence[Mapping[str, str]],
    environment: Mapping[str, Any],
    collected_at: str,
) -> RawEvidenceBundle:
    """Write one immutable raw-run bundle after protocol preflight."""

    _require_timestamp(collected_at, "collected_at")
    _validate_environment(environment)
    scenario = _validate_raw_artifact(protocol, artifact)
    _validate_provider_metadata(artifact.provider_metadata)
    _require_safe_id(protocol.protocol_id, "protocol id")
    run_id = run_id_for(artifact)
    protocol_source = protocol.source_path.read_bytes()
    if _sha256_bytes(protocol_source) != protocol.source_sha256:
        raise EvidenceError("protocol file changed before raw evidence was sealed")

    prompts = [dict(message) for message in effective_prompt]
    if not prompts:
        raise EvidenceError("effective_prompt must retain at least one message")
    for message in prompts:
        if not isinstance(message.get("role"), str) or not isinstance(message.get("content"), str):
            raise EvidenceError("every effective prompt message requires string role and content")
    if not any(
        message["role"] == "user" and message["content"] == scenario.actor.task
        for message in prompts
    ):
        raise EvidenceError("effective prompt does not contain the retained actor task exactly")

    run_record = {
        "format_version": _FORMAT_VERSION,
        "protocol_id": protocol.protocol_id,
        "protocol_sha256": protocol.source_sha256,
        "run_id": run_id,
        "collected_at": collected_at,
        "benchmark_version": artifact.benchmark_version,
        "scenario_id": artifact.scenario_id,
        "scenario_family": artifact.scenario_family,
        "condition": artifact.condition,
        "adapter_id": artifact.adapter_id,
        "adapter_version": artifact.adapter_version,
        "model": artifact.model,
        "repeat_id": artifact.repeat_id,
        "host_capabilities": artifact.host_capabilities.as_dict(),
        "tokens_input": artifact.tokens_input,
        "tokens_output": artifact.tokens_output,
        "elapsed_ms": artifact.elapsed_ms,
        "incomplete": artifact.incomplete,
        "error": artifact.error,
    }
    files = {
        "environment.json": _json_bytes(
            {
                "format_version": _FORMAT_VERSION,
                "captured_at": collected_at,
                "values": dict(environment),
            }
        ),
        "events.jsonl": _jsonl_bytes([_event_record(event) for event in artifact.events]),
        "prompts.json": _json_bytes({"format_version": _FORMAT_VERSION, "messages": prompts}),
        "provider.json": _json_bytes(
            {
                "format_version": _FORMAT_VERSION,
                "metadata": dict(artifact.provider_metadata),
            }
        ),
        "protocol.json": protocol_source,
        "run.json": _json_bytes(run_record),
        "transcript.json": _json_bytes(
            {
                "format_version": _FORMAT_VERSION,
                "messages": [dict(message) for message in artifact.transcript],
            }
        ),
    }
    target = evidence_root / protocol.protocol_id / "runs" / run_id / "raw"
    manifest_sha256 = _commit_bundle(target, files)
    return RawEvidenceBundle(
        path=target.resolve(),
        protocol_id=protocol.protocol_id,
        run_id=run_id,
        manifest_sha256=manifest_sha256,
    )


def _load_raw_artifact(raw_bundle: RawEvidenceBundle, protocol: RunProtocol) -> RunArtifact:
    manifest_sha256 = verify_manifest(raw_bundle.path)
    if manifest_sha256 != raw_bundle.manifest_sha256:
        raise EvidenceError("raw bundle manifest identity changed")
    if (raw_bundle.path / "protocol.json").read_bytes() != protocol.source_path.read_bytes():
        raise EvidenceError("raw bundle protocol snapshot does not match the active protocol")

    run_record = json.loads((raw_bundle.path / "run.json").read_text(encoding="utf-8"))
    if run_record.get("protocol_id") != raw_bundle.protocol_id:
        raise EvidenceError("raw bundle protocol id does not match its handle")
    if run_record.get("run_id") != raw_bundle.run_id:
        raise EvidenceError("raw bundle run id does not match its handle")
    if run_record.get("protocol_sha256") != protocol.source_sha256:
        raise EvidenceError("raw bundle protocol digest does not match the active protocol")

    events: list[BenchmarkEvent] = []
    for line in (raw_bundle.path / "events.jsonl").read_text(encoding="utf-8").splitlines():
        raw_event = json.loads(line)
        events.append(
            BenchmarkEvent(
                kind=EventKind(raw_event["kind"]),
                payload=raw_event["payload"],
                trust=EventTrust(raw_event["trust"]),
                source=raw_event["source"],
            )
        )
    transcript_record = json.loads(
        (raw_bundle.path / "transcript.json").read_text(encoding="utf-8")
    )
    capabilities = run_record["host_capabilities"]
    return RunArtifact(
        benchmark_version=run_record["benchmark_version"],
        scenario_id=run_record["scenario_id"],
        scenario_family=run_record["scenario_family"],
        condition=run_record["condition"],
        adapter_id=run_record["adapter_id"],
        adapter_version=run_record["adapter_version"],
        model=run_record["model"],
        repeat_id=run_record["repeat_id"],
        host_capabilities=HostCapabilities(**capabilities),
        events=tuple(events),
        transcript=tuple(transcript_record["messages"]),
        tokens_input=run_record["tokens_input"],
        tokens_output=run_record["tokens_output"],
        elapsed_ms=run_record["elapsed_ms"],
        provider_metadata=json.loads(
            (raw_bundle.path / "provider.json").read_text(encoding="utf-8")
        )["metadata"],
        incomplete=run_record["incomplete"],
        error=run_record["error"],
    )


def write_evaluation_bundle(
    raw_bundle: RawEvidenceBundle,
    protocol: RunProtocol,
    scenario: Scenario,
    *,
    evaluation_events: Sequence[BenchmarkEvent],
    evaluation_id: str,
    evaluator_id: str,
    evaluator_version: str,
    evaluator_sha256: str,
    evaluated_at: str,
    policy: ScoringPolicy | None = None,
) -> EvaluationEvidenceBundle:
    """Score a retained raw run and append a separately versioned evaluation."""

    assert_ready_for_collection(protocol)
    _require_safe_id(evaluation_id, "evaluation id")
    _require_safe_id(evaluator_id, "evaluator id")
    _require_timestamp(evaluated_at, "evaluated_at")
    if not evaluator_version.strip():
        raise EvidenceError("evaluator_version must be non-empty")
    if not re.fullmatch(r"^[0-9a-f]{64}$", evaluator_sha256):
        raise EvidenceError("evaluator_sha256 must be a SHA-256 digest")

    active_policy = policy or load_scoring_policy(protocol.resolve_repo_file("scoring_policy"))
    policy_ref = protocol.payload["scoring_policy"]
    if not isinstance(policy_ref, Mapping):  # pragma: no cover - readiness invariant
        raise EvidenceError("protocol scoring policy is malformed")
    if active_policy.policy_version != protocol.scoring_policy_version:
        raise EvidenceError("evaluation policy version does not match the protocol")
    if active_policy.source_sha256 != policy_ref.get("sha256"):
        raise EvidenceError("evaluation policy SHA-256 does not match the protocol")
    policy_source = active_policy.source_path.read_bytes()
    if _sha256_bytes(policy_source) != active_policy.source_sha256:
        raise EvidenceError("scoring policy changed before evaluation evidence was sealed")

    for event in evaluation_events:
        if event.trust is not EventTrust.EVALUATOR_DERIVED:
            raise EvidenceError("evaluation bundles accept evaluator-derived events only")
        if event.kind not in _EVALUATOR_EVENT_KINDS:
            raise EvidenceError(f"evaluator cannot originate event kind {event.kind.value}")
        if not event.source.strip():
            raise EvidenceError("every evaluator event must identify its source")
    event_kinds = [event.kind for event in evaluation_events]
    if len(event_kinds) != len(set(event_kinds)):
        raise EvidenceError("evaluation bundle requires one consolidated event per kind")

    raw_artifact = _load_raw_artifact(raw_bundle, protocol)
    retained_scenario = _validate_raw_artifact(protocol, raw_artifact)
    if scenario != retained_scenario:
        raise EvidenceError("evaluation scenario does not match the retained fixture")
    scored_artifact = replace(
        raw_artifact,
        events=raw_artifact.events + tuple(evaluation_events),
    )
    result = score(scored_artifact, retained_scenario, policy=active_policy)

    evaluation_record = {
        "format_version": _FORMAT_VERSION,
        "protocol_id": protocol.protocol_id,
        "run_id": raw_bundle.run_id,
        "evaluation_id": evaluation_id,
        "evaluated_at": evaluated_at,
        "evaluator": {
            "id": evaluator_id,
            "version": evaluator_version,
            "implementation_sha256": evaluator_sha256,
        },
        "raw_bundle": {
            "manifest_sha256": raw_bundle.manifest_sha256,
            "protocol_id": raw_bundle.protocol_id,
            "run_id": raw_bundle.run_id,
        },
        "scoring_policy": {
            "version": active_policy.policy_version,
            "sha256": active_policy.source_sha256,
        },
        "evaluator_event_count": len(evaluation_events),
    }
    files = {
        "evaluation.json": _json_bytes(evaluation_record),
        "evaluator-events.jsonl": _jsonl_bytes(
            [_event_record(event) for event in evaluation_events]
        ),
        "results.jsonl": (result.as_json() + "\n").encode("utf-8"),
        "scoring-policy.json": policy_source,
    }
    target = raw_bundle.path.parent / "evaluations" / active_policy.policy_version / evaluation_id
    manifest_sha256 = _commit_bundle(target, files)
    return EvaluationEvidenceBundle(
        path=target.resolve(),
        protocol_id=protocol.protocol_id,
        run_id=raw_bundle.run_id,
        evaluation_id=evaluation_id,
        manifest_sha256=manifest_sha256,
        result=result,
    )
